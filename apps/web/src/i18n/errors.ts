export function translateError(
  t: (key: MessageKey) => string,
  code: string | null | undefined,
  extra?: Partial<Record<string, MessageKey>>,
): string {
  if (!code) return '';
  const key = extra?.[code] ?? ERROR_TO_KEY[code];
  if (key) return t(key);
  // Already a dictionary key (some screens pass keys straight through).
  if (code in dictionary.en) return t(code as MessageKey);
  // Unknown server code: name it so the cause is visible.
  if (/^[a-z0-9_]+$/.test(code)) return t('errorWithCode').replace('{code}', code);
  return t('errorGeneric');
}
