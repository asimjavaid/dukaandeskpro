-- Lite: tills keep selling while the main PC is down and send the sales later.

-- One row per sale made on a till without the main PC. client_uuid makes sync idempotent.
ALTER TABLE sales ADD COLUMN client_uuid TEXT;
ALTER TABLE sales ADD COLUMN offline_no BIGINT;
ALTER TABLE sales ADD COLUMN synced_at TEXT;
CREATE UNIQUE INDEX idx_sales_client_uuid ON sales (client_uuid) WHERE client_uuid IS NOT NULL;
CREATE UNIQUE INDEX idx_sales_till_offline ON sales (till_id, offline_no) WHERE offline_no IS NOT NULL;

-- Offline bill numbers (T2-OFF-000045) are handed to each till in blocks, so they never collide.
ALTER TABLE tills ADD COLUMN off_alloc_to BIGINT NOT NULL DEFAULT 0;

-- An offline sale is recorded even when stock already ran out: stock may go below zero,
-- and a manager sees it in Stock review.
ALTER TABLE stock_balances DROP CONSTRAINT IF EXISTS stock_balances_qty_on_hand_check;

CREATE TABLE stock_reviews (
  id           TEXT PRIMARY KEY,
  product_id   TEXT NOT NULL REFERENCES products(id) DEFERRABLE INITIALLY IMMEDIATE,
  sale_id      TEXT REFERENCES sales(id) DEFERRABLE INITIALLY IMMEDIATE,
  till_id      TEXT REFERENCES tills(id) DEFERRABLE INITIALLY IMMEDIATE,
  qty_sold     NUMERIC NOT NULL,
  qty_after    NUMERIC NOT NULL,
  created_at   TEXT NOT NULL DEFAULT (sqlite_datetime('now')),
  resolved_at  TEXT,
  resolved_by  TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE,
  note         TEXT,
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX idx_stock_reviews_open ON stock_reviews (created_at) WHERE resolved_at IS NULL;
