-- Shifts: one open shift per till (was one for the whole shop).
ALTER TABLE till_shifts ADD COLUMN till_id TEXT NOT NULL DEFAULT 'till-1' REFERENCES tills(id) DEFERRABLE INITIALLY IMMEDIATE;
DROP INDEX IF EXISTS idx_till_one_open;
CREATE UNIQUE INDEX idx_till_one_open_per_till ON till_shifts (till_id) WHERE closed_at IS NULL;
CREATE INDEX idx_till_shifts_till ON till_shifts (till_id, opened_at DESC);

-- Where money moved. Old rows belong to Till 1.
ALTER TABLE sales ADD COLUMN till_id TEXT NOT NULL DEFAULT 'till-1' REFERENCES tills(id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE sales ADD COLUMN bill_no BIGINT;
CREATE UNIQUE INDEX idx_sales_till_bill ON sales (till_id, bill_no) WHERE bill_no IS NOT NULL;
CREATE INDEX idx_sales_till_recorded ON sales (till_id, recorded_at);
ALTER TABLE sale_returns ADD COLUMN till_id TEXT NOT NULL DEFAULT 'till-1' REFERENCES tills(id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE sale_returns ADD COLUMN approved_by TEXT REFERENCES users(id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE party_ledger ADD COLUMN till_id TEXT NOT NULL DEFAULT 'till-1' REFERENCES tills(id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE expenses ADD COLUMN till_id TEXT NOT NULL DEFAULT 'till-1' REFERENCES tills(id) DEFERRABLE INITIALLY IMMEDIATE;

