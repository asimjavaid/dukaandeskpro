-- Lite slice P3: tills, per-till shifts and bill numbers, manager role, install mode.

CREATE TABLE tills (
  id               TEXT PRIMARY KEY,
  code             BIGINT NOT NULL UNIQUE CHECK (code BETWEEN 1 AND 99),
  name             TEXT NOT NULL,
  kind             TEXT NOT NULL DEFAULT 'remote' CHECK (kind IN ('main', 'remote')),
  device_key_hash  TEXT UNIQUE,
  device_name      TEXT,
  pair_code_hash   TEXT,
  pair_expires_at  TEXT,
  paired_at        TEXT,
  last_seen_at     TEXT,
  next_bill_no     BIGINT NOT NULL DEFAULT 1 CHECK (next_bill_no >= 1),
  active           BIGINT NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at       TEXT NOT NULL DEFAULT (sqlite_datetime('now')),
  updated_at       TEXT NOT NULL DEFAULT (sqlite_datetime('now')),
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY
);

