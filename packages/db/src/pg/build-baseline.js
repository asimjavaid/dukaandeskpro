'use strict';
/**
 * Generates baseline.sql: P1's final schema (all 45 SQLite migrations applied to an empty file),
 * translated to PostgreSQL. Run after changing P1-era migrations:  node packages/db/src/pg/build-baseline.js
 * New Lite schema changes go in packages/db/migrations-pg/NNN_*.sql (PostgreSQL SQL), never here.
 */
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const Database = require('better-sqlite3');
const { migrate } = require('../migrate.js');
const { translate } = require('./translate');

const OUT = path.join(__dirname, 'baseline.sql');
const tmp = path.join(os.tmpdir(), `ddpro-baseline-${process.pid}.sqlite`);
fs.rmSync(tmp, { force: true });
const mig = migrate(tmp);
const db = new Database(tmp, { readonly: true });

const tables = db.prepare(`SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name <> 'schema_migrations' ORDER BY name`).all();
const deps = new Map(tables.map((t) => [t.name, new Set(db.prepare(`SELECT DISTINCT "table" AS t FROM pragma_foreign_key_list(?)`).all(t.name).map((r) => r.t).filter((x) => x !== t.name))]));
const order = [];
const seen = new Set();
function visit(n, stack = []) {
  if (seen.has(n)) return;
  if (stack.includes(n)) throw new Error('FK cycle: ' + [...stack, n].join(' -> '));
  for (const d of deps.get(n) || []) visit(d, [...stack, n]);
  seen.add(n);
  order.push(n);
}
tables.forEach((t) => visit(t.name));

// SQLite INTEGER columns that P1 fills with fractional quantities (25.5 kg, 0.25 kg …): NUMERIC, not BIGINT.
const FRACTIONAL = /^(.*_qty|qty_.*|qty|.*_qty_.*|pieces|delta_pieces|counted_qty|system_qty_snapshot|cost_before|cost_after|packs)$/;
function ddl(sql) {
  let s = sql.replace(/(^|[(,\s])([a-z_][a-z0-9_]*)(\s+)INTEGER\b/g, (m, pre, col, sp) => (FRACTIONAL.test(col) ? `${pre}${col}${sp}NUMERIC` : m));
  s = s
    .replace(/\bINTEGER\b/gi, 'BIGINT')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/gi, 'BYTEA')
    .replace(/\bAUTOINCREMENT\b/gi, '')
    .replace(/(REFERENCES\s+"?\w+"?\s*(?:\([^)]*\))?(?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:CASCADE|SET\s+NULL|SET\s+DEFAULT|RESTRICT|NO\s+ACTION))*)/gi, '$1 DEFERRABLE INITIALLY IMMEDIATE');
  s = translate(s, [], { keepCase: true });
  return s;
}

const out = [];
out.push('-- GENERATED by packages/db/src/pg/build-baseline.js from P1 migrations ' + mig.applied[0] + ' .. ' + mig.applied[mig.applied.length - 1] + ' (' + mig.applied.length + ' files). Do not edit.');
out.push('-- Every table gets a hidden "rowid" identity column so P1 queries that order/mark by rowid keep working.');
for (const name of order) {
  const t = tables.find((x) => x.name === name);
  let s = ddl(t.sql).replace(/\)\s*$/, ',\n  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY\n)');
  out.push(s + ';');
}
for (const ix of db.prepare(`SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY name`).all()) out.push(ddl(ix.sql) + ';');
// seed rows created by migrations
for (const name of order) {
  const rows = db.prepare(`SELECT * FROM "${name}"`).all();
  const { lit } = require('./translate');
  for (const r of rows) {
    const cols = Object.keys(r);
    out.push(`INSERT INTO ${name} (${cols.join(', ')}) VALUES (${cols.map((c) => lit(r[c])).join(', ')});`);
  }
}
out.push(fs.readFileSync(path.join(__dirname, 'triggers.sql'), 'utf8'));
fs.writeFileSync(OUT, out.join('\n\n') + '\n');
fs.writeFileSync(path.join(__dirname, 'baseline-migrations.json'), JSON.stringify(mig.applied, null, 1));
db.close();
fs.rmSync(tmp, { force: true });
console.log(`baseline.sql: ${order.length} tables, ${mig.applied.length} P1 migrations squashed`);
